export type Copy = (typeof copy)[keyof typeof copy];

const MODE_LABEL_KEYS = {
  independent: 'modeIndependentTitle',
  debate: 'modeDebateTitle',
  chain: 'modeChainTitle',
} as const;

export const modeLabel = (mode: keyof typeof MODE_LABEL_KEYS, language: Language) =>
  copy[language][MODE_LABEL_KEYS[mode]];

/** Both language tables must carry every key; tsc enforces it, this is the runtime guard. */
export const missingCopyKeys = (language: Language): string[] => {
  const source = Object.keys(copy.en) as (keyof typeof copy.en)[];
  return source.filter((key) => !(key in copy[language]));
};
/**
 * Copy keys whose value is a string. `keyof Copy` alone would also accept `legal`, which is a
 * tree of documents rather than a sentence, and every caller of `t()` renders a bare string.
 */
export type CopyStringKey = {
  [K in keyof Copy]: Copy[K] extends string ? K : never;
}[keyof Copy];

export const t = (language: 'en' | 'vi', key: CopyStringKey): string => copy[language][key];
